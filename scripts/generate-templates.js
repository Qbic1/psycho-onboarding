/**
 * Генератор шаблонов документов для раздела «Файлы для скачивания».
 * Запуск: node scripts/generate-templates.js
 * Зависимость: docx (devDependencies). Файлы создаются в static/templates/.
 */
const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell,
  AlignmentType, WidthType, ShadingType, VerticalAlign,
} = require("docx");
const fs = require("fs");
const path = require("path");

const OUT_DIR = path.join(__dirname, "..", "static", "templates");
fs.mkdirSync(OUT_DIR, { recursive: true });

const FONT = "Times New Roman";
const BODY = 24; // 12 pt
const SMALL = 22; // 11 pt
const HEAD = 26; // 13 pt
const TITLE = 28; // 14 pt

const PAGE = { margin: { top: 1134, bottom: 1134, left: 1701, right: 850 } };
const LINE = 312; // 1.3x

// ---------- helpers ----------

function run(text, o = {}) {
  return new TextRun({
    text,
    size: o.size ?? BODY,
    bold: o.bold,
    italics: o.italics,
    color: o.color,
  });
}

function p(text, o = {}) {
  return new Paragraph({
    alignment: o.align ?? AlignmentType.JUSTIFIED,
    spacing: { line: LINE, after: o.after ?? 100, before: o.before ?? 0 },
    keepNext: o.keepNext,
    pageBreakBefore: o.pageBreakBefore,
    children: Array.isArray(text) ? text : [run(text, o)],
  });
}

function empty(o = {}) {
  return new Paragraph({ spacing: { line: LINE, after: o.after ?? 100 }, children: [] });
}

function docTitle(text, o = {}) {
  return p(text, {
    align: AlignmentType.CENTER, bold: true, size: o.size ?? TITLE,
    before: o.before ?? 120, after: o.after ?? 40, keepNext: true,
  });
}

function sub(text) {
  return p(text, { align: AlignmentType.CENTER, size: BODY, after: 200, keepNext: true });
}

function h(text, o = {}) {
  return p(text, {
    align: AlignmentType.LEFT, bold: true, size: o.size ?? HEAD,
    before: o.before ?? 200, after: 80, keepNext: true,
    pageBreakBefore: o.pageBreakBefore,
  });
}

function field(label, blank) {
  return p(`${label}${blank ?? "________________________________________"}`, { align: AlignmentType.LEFT, after: 60 });
}

const noBorder = { style: BorderStyleNone(), size: 0, color: "FFFFFF" };
function BorderStyleNone() { return "none"; }

function borderlessTable(cellsPercent, rowsOfParas) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: tableBordersNone(),
    rows: rowsOfParas.map(
      (paras) =>
        new TableRow({
          cantSplit: true,
          children: cellsPercent.map(
            (w, i) =>
              new TableCell({
                width: { size: w, type: WidthType.PERCENTAGE },
                borders: cellBordersNone(),
                margins: { top: 0, bottom: 0, left: 0, right: 100 },
                children: paras[i] ?? [new Paragraph({ children: [] })],
              })
          ),
        })
    ),
  });
}

function tableBordersNone() {
  return {
    top: noBorder, bottom: noBorder, left: noBorder, right: noBorder,
    insideHorizontal: noBorder, insideVertical: noBorder,
  };
}
function cellBordersNone() {
  return { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder };
}

// Блок «Директору … от …» — в правой половине листа
function addressee(lines) {
  return borderlessTable(
    [42, 58],
    lines.map((t) => [
      [new Paragraph({ children: [] })],
      [p(t, { align: AlignmentType.LEFT, after: 20, size: SMALL })],
    ])
  );
}

// Подпись: дата слева, подпись справа
function signRow(leftText, rightText) {
  return borderlessTable(
    [45, 55],
    [[
      [p(leftText, { align: AlignmentType.LEFT, after: 0, size: SMALL })],
      [p(rightText, { align: AlignmentType.RIGHT, after: 0, size: SMALL })],
    ]]
  );
}

function cellText(text, o = {}) {
  return new TableCell({
    width: o.width ? { size: o.width, type: WidthType.PERCENTAGE } : undefined,
    shading: o.header ? { type: ShadingType.CLEAR, fill: "E8F1EF" } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [
      new Paragraph({
        alignment: o.align ?? AlignmentType.LEFT,
        spacing: { line: 276 },
        children: [run(text, { size: o.size ?? SMALL, bold: o.header })],
      }),
    ],
  });
}

function grid(headers, widths, rows, o = {}) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        tableHeader: true,
        cantSplit: true,
        children: headers.map((t, i) => cellText(t, { header: true, width: widths[i], align: AlignmentType.CENTER, size: o.size })),
      }),
      ...(rows.length
        ? rows.map((r) => new TableRow({ cantSplit: true, children: r.map((t, i) => cellText(t, { width: widths[i], size: o.size })) }))
        : [new TableRow({ cantSplit: true, children: widths.map((w) => cellText("", { width: w })) })]),
    ],
  });
}

// пустые строки-заготовки для журналов (N одинаковых пустых строк)
function blankRows(n, count) {
  return Array.from({ length: count }, () => n.map(() => ""));
}

const approveBlock = (titleLeft) =>
  borderlessTable([55, 45], [
    [
      [p(titleLeft ?? "УТВЕРЖДАЮ", { align: AlignmentType.LEFT, bold: true, after: 20, size: SMALL })],
      [p("Директор ________________", { align: AlignmentType.LEFT, after: 20, size: SMALL })],
    ],
    [
      [p("(наименование ОО)", { align: AlignmentType.LEFT, after: 20, size: SMALL })],
      [p("____________ /______________/", { align: AlignmentType.LEFT, after: 20, size: SMALL })],
    ],
    [
      [empty({ after: 0 })],
      [p("«____» ____________ 20___ г.", { align: AlignmentType.LEFT, after: 0, size: SMALL })],
    ],
  ]);

function makeDoc(children) {
  return new Document({
    styles: {
      default: {
        document: {
          run: { font: FONT, size: BODY, color: "000000" },
          paragraph: { spacing: { line: LINE } },
        },
      },
    },
    sections: [{ properties: { page: PAGE }, children }],
  });
}

async function writeDoc(name, children) {
  const buf = await Packer.toBuffer(makeDoc(children));
  fs.writeFileSync(path.join(OUT_DIR, name), buf);
  console.log("OK", name);
}

